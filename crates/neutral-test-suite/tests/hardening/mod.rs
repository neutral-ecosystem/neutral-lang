/// Current minimal source used as the seed for hardening campaigns.
const MINIMAL_SOURCE: &[u8] = b"neu \"1.0\"\nmodule hardening\npublic num answer = 42\n";
/// Valid current-schema composition vocabulary used as the mutation seed.
const VOCABULARY_BUNDLE: &[u8] =
    include_bytes!("../../../neutral-vocabulary/tests/composition/fixtures/bundle.json");
/// Reproducible seed shared by all stable hardening campaigns.
const HARDENING_FUZZ_SEED: u64 = 0x4e45_5554_5241_4c39;
/// Stable number of cases exercised by each fast campaign.
const HARDENING_FUZZ_CASES: usize = 1_024;
/// Largest arbitrary source or vocabulary input generated by fast campaigns.
const HARDENING_MAX_INPUT_BYTES: usize = 1_024;
/// Current fixture vocabulary identity.
const FIXTURE_VOCABULARY_IDENTITY: &str = "ExampleDomain";
/// Current fixture vocabulary release.
const FIXTURE_VOCABULARY_VERSION: &str = "1.0.0";

/// Returns generous deterministic limits for hostile and property campaigns.
fn campaign_limits() -> StructuralLimits {
    StructuralLimits::new(16_384, 16).expect("campaign limits must be nonzero")
}

/// Builds exact current capture controls for one explicit source without discovery.
fn captured(source: &[u8], cancel: &CancellationToken) -> Result<CapturedExpressionProject, ()> {
    let bytes = campaign_limits().source_bytes();
    let scalar = campaign_limits();
    capture_expression_project(CapturedExpressionProjectRequest::new(
        CapturedProjectRequest::new(
            profile::CAPTURE_REQUEST_VERSION,
            LanguageProfile::V1_0,
            vec![CapturedSourceInput::new(
                "suite:hardening",
                "hardening",
                source.to_vec(),
            )],
            Vec::new(),
            ProjectCaptureControls::new(
                ProjectCaptureLimits::new(ProjectCaptureLimitValues {
                    total_source_bytes: bytes,
                    source_bytes_per_unit: bytes,
                    source_units: 1,
                    source_id_bytes: 64,
                    module_id_bytes: 64,
                    vocabulary_units: 1,
                    vocabulary_bytes_per_unit: bytes,
                    total_vocabulary_bytes: bytes,
                    imports_per_module: 1,
                    import_edges: 1,
                    scc_units: 1,
                    declarations: 64,
                    diagnostics: 16,
                    output_bytes: bytes,
                }),
                cancel.clone(),
            ),
        ),
        SemanticProfiles::try_frozen().map_err(|_| ())?,
        CompositionLimits::from_vocabulary(VocabularyLimits::from_structural(scalar)),
        ExpressionLimits::hard(),
        ExpansionLimits::hard(),
    ))
    .map_err(|_| ())
}

/// Captures, compiles, validates and encodes through the current complete project pipeline.
fn current_artifact(source: &[u8]) -> Result<(Vec<u8>, ValidatedExpressionProject), ()> {
    let cancel = CancellationToken::new();
    let capture = captured(source, &cancel)?;
    let ir = compile_expression_project(&capture, &cancel).map_err(|_| ())?;
    let semantic = SemanticLimits {
        project: ir.limits,
        composition: capture.composition_limits(),
        expression: capture.expression_limits(),
        expansion: capture.expansion_limits(),
    };
    let authority = ValidatedExpressionProject::from_ir(ir, semantic, &cancel).map_err(|_| ())?;
    let bytes = encode_expression_project(&authority, &cancel).map_err(|_| ())?;
    Ok((bytes, authority))
}

/// Formats one exact current source through the captured-project formatter.
fn formatted(source: &[u8]) -> Result<Vec<u8>, ()> {
    let cancel = CancellationToken::new();
    let captured = captured(source, &cancel)?;
    format_expression_source(&captured, "hardening", &cancel).map_err(|_| ())
}

/// Creates a lock whose digest matches the exact supplied vocabulary bytes.
fn vocabulary_lock(bytes: &[u8]) -> VocabularyLock {
    VocabularyLock::new(
        FIXTURE_VOCABULARY_IDENTITY,
        FIXTURE_VOCABULARY_VERSION,
        ENCODING_VERSION,
        SCHEMA_VERSION,
        VocabularyContentDigest::from_bytes(bytes),
        vec![REQUIRED_FEATURE.to_owned()],
    )
    .expect("fixture lock constants must remain valid")
}

/// Advances the reproducible xorshift generator used by stable campaigns.
fn fuzz_word(state: &mut u64) -> u64 {
    *state ^= *state << 13;
    *state ^= *state >> 7;
    *state ^= *state << 17;
    *state
}

/// Generates one bounded deterministic arbitrary byte vector.
fn arbitrary_bytes(state: &mut u64) -> Vec<u8> {
    let length = usize::try_from(
        fuzz_word(state) % u64::try_from(HARDENING_MAX_INPUT_BYTES + 1).unwrap_or(u64::MAX),
    )
    .unwrap_or_default();
    (0..length)
        .map(|_| fuzz_word(state).to_le_bytes()[0])
        .collect()
}

#[test]
/// Current source identity and formatting remain stable under harmless transforms.
fn property_complete_metamorphic_composition_matrix() {
    let (_, baseline) = current_artifact(MINIMAL_SOURCE).unwrap();
    let variants = [
        MINIMAL_SOURCE.to_vec(),
        String::from_utf8(MINIMAL_SOURCE.to_vec())
            .expect("fixture source must be UTF-8")
            .replace('\n', "\r\n")
            .into_bytes(),
        [
            b"neu \"1.0\"\nmodule hardening\n// hardening\n".as_slice(),
            b"public num answer = 42\n",
        ]
        .concat(),
    ];
    for variant in variants {
        let (_, project) = current_artifact(&variant).unwrap();
        let limits = |project: &ValidatedExpressionProject| IdentityLimits {
            bytes: project.model().limits().project.artifact_bytes,
            nodes: project.model().limits().project.nodes,
        };
        assert_eq!(
            canonical_expression_project(
                baseline.ir(),
                limits(&baseline),
                &CancellationToken::new()
            )
            .unwrap(),
            canonical_expression_project(project.ir(), limits(&project), &CancellationToken::new())
                .unwrap(),
        );
        assert_eq!(
            expression_interface(baseline.ir(), limits(&baseline), &CancellationToken::new())
                .unwrap(),
            expression_interface(project.ir(), limits(&project), &CancellationToken::new())
                .unwrap(),
        );
        let output = formatted(&variant).expect("valid variant must format");
        let reformatted = formatted(&output).expect("formatted variant must format again");
        assert_eq!(output, reformatted);
    }
}

#[test]
/// Proves repeated and concurrent adversarial executions retain identical results.
fn property_adversarial_repeated_and_concurrent_determinism() {
    let inputs = [
        MINIMAL_SOURCE.to_vec(),
        Vec::new(),
        vec![0xff; 257],
        b"neu \"1.0\"\nmodule x\npublic List<string> values = [\"a\", \"b\"]\n".to_vec(),
    ];
    for input in inputs {
        let expected = current_artifact(&input).map(|(bytes, _)| bytes);
        let handles = (0..8)
            .map(|_| {
                let input = input.clone();
                thread::spawn(move || current_artifact(&input).map(|(bytes, _)| bytes))
            })
            .collect::<Vec<_>>();
        for handle in handles {
            assert_eq!(
                handle.join().expect("campaign worker must not panic"),
                expected
            );
        }
    }
}

#[test]
/// Proves separately captured requests cannot reuse stale source identity facts.
fn security_cross_request_source_fact_isolation() {
    let first = b"neu \"1.0\"\nmodule hardening\npublic string value = \"a\"\n";
    let second = b"neu \"1.0\"\nmodule hardening\npublic string value = \"b\"\n";
    for (source, other) in [
        (first.as_slice(), second.as_slice()),
        (second.as_slice(), first.as_slice()),
    ] {
        let (_, project) = current_artifact(source).unwrap();
        assert_eq!(
            project.ir().sources[0].digest,
            SourceContentDigest::from_bytes(source)
        );
        assert_ne!(
            project.ir().sources[0].digest,
            SourceContentDigest::from_bytes(other)
        );
    }
}

#[test]
/// Runs arbitrary current sources through bounded capture, compilation, and wire encoding.
fn fuzz_source_pipeline_campaign_terminates() {
    let mut state = HARDENING_FUZZ_SEED;
    for _ in 0..HARDENING_FUZZ_CASES {
        let bytes = arbitrary_bytes(&mut state);
        let _ = current_artifact(&bytes);
    }
}

#[test]
/// Runs the bounded arbitrary vocabulary JSON and schema campaign.
fn fuzz_vocabulary_pipeline_campaign_terminates() {
    let mut state = HARDENING_FUZZ_SEED;
    for _ in 0..HARDENING_FUZZ_CASES {
        let bytes = arbitrary_bytes(&mut state);
        let lock = vocabulary_lock(&bytes);
        let input = [CapturedCompositionBundle {
            bytes: &bytes,
            lock: &lock,
        }];
        let _ = validate_composition_closure(
            &input,
            &[(FIXTURE_VOCABULARY_IDENTITY, FIXTURE_VOCABULARY_VERSION)],
            CompositionLimits::from_vocabulary(
                VocabularyLimits::from_structural(campaign_limits()),
            ),
            &CancellationToken::new(),
        );
    }
    let lock = vocabulary_lock(VOCABULARY_BUNDLE);
    assert!(
        validate_composition_closure(
            &[CapturedCompositionBundle {
                bytes: VOCABULARY_BUNDLE,
                lock: &lock,
            }],
            &[(FIXTURE_VOCABULARY_IDENTITY, FIXTURE_VOCABULARY_VERSION)],
            CompositionLimits::from_vocabulary(
                VocabularyLimits::from_structural(campaign_limits())
            ),
            &CancellationToken::new(),
        )
        .is_ok()
    );
}

#[test]
/// Runs the bounded formatted-source campaign and rechecks every accepted result.
fn fuzz_formatter_pipeline_campaign_terminates() {
    let mut state = HARDENING_FUZZ_SEED;
    for _ in 0..HARDENING_FUZZ_CASES {
        let bytes = arbitrary_bytes(&mut state);
        if let Ok(output) = formatted(&bytes) {
            let second =
                formatted(&output).expect("accepted formatter output must remain accepted");
            assert_eq!(output, second);
        }
    }
}

#[test]
/// Runs structured arbitrary mutations through current `/3` framing and decoding.
fn fuzz_ir_pipeline_campaign_terminates() {
    let (encoded, project) = current_artifact(MINIMAL_SOURCE).unwrap();
    let limits = project.model().limits();
    let mut state = HARDENING_FUZZ_SEED;
    for _ in 0..HARDENING_FUZZ_CASES {
        let mut bytes = encoded.clone();
        let index = usize::try_from(fuzz_word(&mut state) % bytes.len() as u64).unwrap_or_default();
        bytes[index] ^= fuzz_word(&mut state).to_le_bytes()[0].max(1);
        let _ = decode_expression_project(
            &bytes,
            DecodeLimits::hard(),
            limits,
            &CancellationToken::new(),
        );
    }
}

